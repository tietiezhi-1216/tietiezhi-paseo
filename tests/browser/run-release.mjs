import { build } from "esbuild";
import { chromium } from "playwright";
import { createServer } from "node:http";
import { mkdtemp,readFile,rm,mkdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join,resolve } from "node:path";
import { existsSync } from "node:fs";
import assert from "node:assert/strict";
const root=resolve("."),temp=await mkdtemp(join(tmpdir(),"tietiezhi-release-ui-"));
let browser,server;
try{
  await build({entryPoints:[join(root,"tests/browser/release.jsx")],outfile:join(temp,"app.js"),bundle:true,format:"iife",platform:"browser",jsx:"automatic",define:{"process.env.NODE_ENV":'"test"'},alias:{"react-native":"react-native-web"},plugins:[{name:"sdk",setup(b){b.onResolve({filter:/^@getpaseo\/plugin\/client(?:\/(react-native|ui))?$/},()=>({path:join(root,"tests/browser/release-sdk.jsx")}));}}]});
  server=createServer(async(req,res)=>{if(req.url==="/app.js"){res.setHeader("Content-Type","application/javascript");res.end(await readFile(join(temp,"app.js")));return;}res.end('<html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0}</style><div id="root"></div><script src="/app.js"></script></html>');});
  await new Promise(done=>server.listen(0,"127.0.0.1",done));
  const chrome=process.env.CHROME_PATH||"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
  browser=await chromium.launch({headless:true,...existsSync(chrome)?{executablePath:chrome}:{}});
  await mkdir(".artifacts/ui",{recursive:true});
  for(const mobile of [false,true]){
    const page=await browser.newPage({viewport:mobile?{width:390,height:844}:{width:1100,height:1000},hasTouch:mobile});
    const errors=[];page.on("pageerror",error=>errors.push(String(error)));
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    if(mobile)await page.evaluate(()=>globalThis.__release.light(true));
    await page.getByRole("button",{name:"发布记录",exact:true}).click();
    const board=page.getByTestId("tietiezhi-release-board");await board.waitFor();
    await board.getByText("站点可访问",{exact:true}).waitFor();
    await board.getByText("local-only 修复部署中的累计发布",{exact:true}).first().waitFor();
    assert.equal(await board.getByLabel("GitHub 部署",{exact:true}).count(),1);
    assert.equal(await board.getByLabel("SVN 部署",{exact:true}).count(),1);
    await page.getByRole("button",{name:"SVN",exact:true}).click();
    await board.getByText("修复中文日志与对接记录",{exact:true}).waitFor();
    assert.equal(await board.getByText("文档回执",{exact:true}).count(),0);
    assert.equal(await board.getByLabel("GitHub 部署",{exact:true}).count(),1,"deployments stay above history across tabs");
    await page.getByRole("button",{name:/r1300/}).click();
    await board.getByText("作者: SVN提交人",{exact:false}).first().waitFor();
    await page.getByRole("button",{name:"GIT",exact:true}).click();
    await page.getByRole("button",{name:/#547 local-only/}).click();
    await board.getByRole("link",{name:"在浏览器打开记录",exact:true}).click();
    assert.equal(await page.evaluate(()=>globalThis.__release.calls.at(-1).url),"https://github.com/example/pull/547");
    await page.screenshot({path:`.artifacts/ui/release-${mobile?"mobile-light":"desktop-dark"}.png`,fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.evaluate(()=>globalThis.__release.fail());
    await board.getByText("站点待确认",{exact:true}).waitFor();
    assert.ok(await board.getByText("状态待确认",{exact:true}).count()>0);
    assert.equal(await board.getByText("无需运行时发布",{exact:true}).count(),1,"historical completion does not regress after health failure");
    await page.evaluate(()=>globalThis.__release.online(false));
    await board.getByText("当前 Host 离线，保留上次记录；不会切换到其他设备",{exact:true}).waitFor();
    await page.evaluate(()=>{globalThis.__release.online(true);globalThis.__release.host("remote");});
    await page.getByRole("button",{name:"发布记录",exact:true}).click();
    await board.getByText("remote-only 修复部署中的累计发布",{exact:true}).first().waitFor();
    assert.equal(await board.getByText("local-only 修复部署中的累计发布",{exact:true}).count(),0);
    await page.getByRole("button",{name:"SVN",exact:true}).click();
    await board.getByText("修复中文日志与对接记录",{exact:true}).waitFor();
    await page.evaluate(()=>globalThis.__release.mount(false));
    await page.evaluate(()=>globalThis.__release.mount(true));
    await page.getByRole("button",{name:"发布记录",exact:true}).click();
    await board.getByText("修复中文日志与对接记录",{exact:true}).waitFor();
    assert.deepEqual(errors,[]);
    await page.close();
  }
  console.log("Release board desktop/mobile passed: manager tab, channels, both deployments, details, external links, stale history, Host isolation and persisted preferences (mock RPC).");
}finally{await browser?.close();if(server)await new Promise(done=>server.close(done));await rm(temp,{recursive:true,force:true});}
